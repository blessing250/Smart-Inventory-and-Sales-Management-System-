import { closeSync, openSync, writeSync } from 'node:fs';
import { isAbsolute } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { migrations } from '../backend/database/business-schema.ts';
import { verifyDatabase } from './database.mjs';

const identifier = value => '"' + value.replaceAll('"', '""') + '"';
const insertionOrdered = new Set(['stock_movements', 'stock_counts', 'shipment_receiving_events', 'shipment_resolutions']);

function postgresSql(sql) {
  return sql.replace(/\)\s*STRICT\s*$/, ')')
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bBLOB\b/g, 'BYTEA')
    .replace(/\bCOLLATE NOCASE\b/g, 'COLLATE bizflow_nocase');
}

function copyField(value) {
  if (value === null) return '\\N';
  const data = value instanceof Uint8Array ? '\\x' + Buffer.from(value).toString('hex') : String(value);
  if (data.includes('\0')) throw new Error('PostgreSQL text fields cannot contain NUL characters.');
  return data.replaceAll('\\', '\\\\').replaceAll('\t', '\\t').replaceAll('\r', '\\r').replaceAll('\n', '\\n');
}

function exportSnapshot(filename, destination, schema) {
  if (!isAbsolute(filename) || !isAbsolute(destination) || !/^[a-z][a-z0-9_]{0,47}$/.test(schema)) {
    throw new Error('Use absolute paths and a new PostgreSQL schema name, such as bizflow_stage.');
  }
  if (verifyDatabase(filename) !== migrations.length) throw new Error('Export a verified snapshot at the current BizFlow schema version.');

  const source = new DatabaseSync(filename, { readOnly: true });
  const reference = new DatabaseSync(':memory:');
  try {
    for (const migration of migrations) reference.exec(migration.sql);
    const objects = reference.prepare(`SELECT type,name,sql FROM sqlite_schema
      WHERE sql IS NOT NULL AND type IN ('table','index','view') ORDER BY rowid`).all();
    const pending = objects.filter(row => row.type === 'table');
    const ordered = [];
    while (pending.length) {
      const index = pending.findIndex(table => reference.prepare('SELECT "table" FROM pragma_foreign_key_list(?)')
        .all(table.name).every(fk => fk.table === table.name || ordered.some(parent => parent.name === fk.table)));
      if (index < 0) throw new Error('The schema contains circular table dependencies.');
      ordered.push(pending.splice(index, 1)[0]);
    }

    source.exec('BEGIN');
    const fd = openSync(destination, 'wx', 0o600);
    try {
      const write = line => writeSync(fd, line + '\n');
      write('\\set ON_ERROR_STOP on\nBEGIN;');
      write(`CREATE SCHEMA ${identifier(schema)};\nSET LOCAL search_path = ${identifier(schema)}, pg_catalog;`);
      write("CREATE COLLATION bizflow_nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false);");
      write(`CREATE TABLE bizflow_schema_version (version BIGINT PRIMARY KEY);
INSERT INTO bizflow_schema_version VALUES (${migrations.length});
CREATE FUNCTION instr(text, text) RETURNS integer LANGUAGE sql IMMUTABLE STRICT AS 'SELECT strpos($1, $2)';
CREATE FUNCTION printf(text, bigint, bigint) RETURNS text LANGUAGE sql IMMUTABLE STRICT AS
  'SELECT $2::text || ''.'' || lpad($3::text, CASE WHEN $1 = ''%d.%02d'' THEN 2 ELSE 6 END, ''0'')';`);
      for (const table of ordered) write(postgresSql(table.sql) + ';');
      for (const table of ordered.filter(row => row.name !== 'password_resets')) {
        const name = identifier(table.name);
        const columnNames = reference.prepare('SELECT name FROM pragma_table_info(?) ORDER BY cid').all(table.name)
          .map(column => column.name);
        const preserveOrder = insertionOrdered.has(table.name);
        if (preserveOrder) {
          write(`ALTER TABLE ${name} ADD COLUMN rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;`);
          columnNames.push('rowid');
        }
        const columns = columnNames.map(identifier).join(', ');
        const rows = source.prepare(`SELECT ${columns} FROM ${name}`);
        rows.setReadBigInts(true);
        let count = 0;
        write(`COPY ${name} (${columns}) FROM STDIN;`);
        for (const row of rows.iterate()) {
          write(Object.values(row).map(copyField).join('\t'));
          count++;
        }
        write('\\.');
        if (preserveOrder) {
          write(`SELECT setval(pg_get_serial_sequence('${name}', 'rowid'), GREATEST(1, max(rowid)), COALESCE(max(rowid) >= 1, false)) FROM ${name};`);
        }
        write(`DO $$ BEGIN IF (SELECT count(*) FROM ${name}) <> ${count} THEN RAISE EXCEPTION 'Row count mismatch: ${table.name}'; END IF; END $$;`);
      }
      for (const object of objects.filter(row => row.type !== 'table')) write(postgresSql(object.sql) + ';');
      write('COMMIT;');
    } finally {
      closeSync(fd);
    }
  } finally {
    source.close();
    reference.close();
  }
}

try {
  const [filename, destination, schema = 'bizflow_stage'] = process.argv.slice(2);
  if (!filename || !destination) throw new Error('Usage: node scripts/export-postgres.mjs ABSOLUTE_SNAPSHOT ABSOLUTE_NEW_SQL_FILE [NEW_SCHEMA]');
  exportSnapshot(filename, destination, schema);
  console.log('Created PostgreSQL import file. Treat it as a private database backup.');
} catch (error) {
  console.error(error.code ? 'PostgreSQL export failed. Check paths, permissions and schema compatibility.' : error.message);
  process.exitCode = 1;
}
